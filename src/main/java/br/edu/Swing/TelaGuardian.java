    private void BotaoVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotaoVerificarActionPerformed
       
       // PEGA A SENHA DIGITADA
        char[] senha = CampoSenha.getPassword();
        
        try {
            // BARRAR SENHAS VAZIAS
            if (senha.length == 0 ){
                Mensagem.setText("Você não pode mandar senha vazia");
                return;
            }
            
            br.edu.Hash.HashUtil hashUtil = new br.edu.Hash.HashUtil();
            String hash = hashUtil.calcularHash(senha);

            br.edu.API.PwnedPasswords api = new br.edu.API.PwnedPasswords();
            String ocorrencias = api.consultar(hash);

            if (ocorrencias.equals("0")) {
                Mensagem.setText("Nenhuma ocorrência encontrada."); // substitua "Mensagem" pelo nome do seu JLabel de resposta
            } else {
                Mensagem.setText("Quantidade de vazamentos: " + ocorrencias);
            }
            
        } catch (InterruptedException ex) {
            Thread.currentThread().interrupt();
            Mensagem.setText("Consulta interrompida.");
        } catch (java.io.IOException ex) {
            Mensagem.setText("Erro ao consultar a API.");
        }
        java.util.Arrays.fill(senha, '\0');

    }//GEN-LAST:event_BotaoVerificarActionPerformed

